-- -----------------------------------------------------------------------------
-- 4. Privileges: SELECT only, for the agent role only
-- -----------------------------------------------------------------------------
GRANT SELECT ON customers, products, orders, order_items TO sql_agent_ro;

-- Row-level security as an extra layer: only the agent role gets a (read-only)
-- policy, so any other non-owner role sees nothing even if it was granted access.
ALTER TABLE customers   ENABLE ROW LEVEL SECURITY;
ALTER TABLE products    ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders      ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_items ENABLE ROW LEVEL SECURITY;

CREATE POLICY agent_read_only ON customers   FOR SELECT TO sql_agent_ro USING (true);
CREATE POLICY agent_read_only ON products    FOR SELECT TO sql_agent_ro USING (true);
CREATE POLICY agent_read_only ON orders      FOR SELECT TO sql_agent_ro USING (true);
CREATE POLICY agent_read_only ON order_items FOR SELECT TO sql_agent_ro USING (true);

-- Supabase grants table access to its API roles by default. Revoke it so the
-- demo data is not exposed over the public REST API. (No-op on plain Postgres.)
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON customers, products, orders, order_items FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON customers, products, orders, order_items FROM authenticated;
    END IF;
END
$$;

COMMIT;
