-- =============================================================================
-- Self-Healing SQL Agent: database bootstrap
--
-- * Creates the dedicated READ-ONLY role the application connects as.
-- * Creates a small e-commerce schema: customers, products, orders, order_items.
--   NOTE: orders uses "order_date" (NOT "created_at"). LLMs often guess
--   "created_at", which makes a realistic self-healing demo.
-- * Seeds data with dates RELATIVE to the day this script runs, so
--   "What was last month's revenue?" always has a real answer.
--
-- Run as an admin user (docker-entrypoint does this automatically), e.g.:
--   psql "$ADMIN_DATABASE_URL" -v ON_ERROR_STOP=1 -f db/init.sql
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- 1. Read-only application role
-- -----------------------------------------------------------------------------
-- Dev-only default password. Rotate it on any shared/remote database:
--   ALTER ROLE sql_agent_ro PASSWORD '<strong-random-password>';
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sql_agent_ro') THEN
        CREATE ROLE sql_agent_ro WITH
            LOGIN PASSWORD 'sql_agent_ro_dev_password'
            NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS NOINHERIT
            CONNECTION LIMIT 20;
    END IF;
END
$$;

-- Server-side guard rails that apply even if the app forgets its own.
ALTER ROLE sql_agent_ro SET default_transaction_read_only = on;
ALTER ROLE sql_agent_ro SET statement_timeout = '10s';
ALTER ROLE sql_agent_ro SET idle_in_transaction_session_timeout = '15s';

DO $$
BEGIN
    EXECUTE format('GRANT CONNECT ON DATABASE %I TO sql_agent_ro', current_database());
END
$$;

-- PostgreSQL 15+ already revokes CREATE on schema public from PUBLIC, so the
-- role cannot create objects; it only needs USAGE to resolve names.
GRANT USAGE ON SCHEMA public TO sql_agent_ro;

-- -----------------------------------------------------------------------------
-- 2. Schema
-- -----------------------------------------------------------------------------
CREATE TABLE customers (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   text        NOT NULL,
    email       text        NOT NULL UNIQUE,
    country     text        NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE products (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text          NOT NULL,
    category    text          NOT NULL,
    unit_price  numeric(10,2) NOT NULL CHECK (unit_price >= 0)
);

CREATE TABLE orders (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  integer NOT NULL REFERENCES customers (id),
    order_date   date    NOT NULL,
    status       text    NOT NULL
        CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled'))
);

CREATE TABLE order_items (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    integer       NOT NULL REFERENCES orders (id),
    product_id  integer       NOT NULL REFERENCES products (id),
    quantity    integer       NOT NULL CHECK (quantity > 0),
    unit_price  numeric(10,2) NOT NULL CHECK (unit_price >= 0)
);

CREATE INDEX orders_order_date_idx ON orders (order_date);
CREATE INDEX order_items_order_id_idx ON order_items (order_id);

